import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { checkIcon } from "./check-icons.ts";
import { type Element, parseIcon } from "./icon-xml.ts";

export function generateIcons(directory = "src/icon/svg") {
  function reactTree(element: Element): unknown {
    return {
      tag: element.name,
      attrs: Object.fromEntries(
        Object.entries(element.attrs).map(([key, value]) => [
          key.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase()),
          value,
        ]),
      ),
      children: element.children.map(reactTree),
    };
  }
  const files = readdirSync(directory)
    .filter((file) => file.endsWith(".svg"))
    .sort();
  if (!files.length) throw new Error(`${directory}: no SVG icons found`);
  const entries = files.map((file) => {
    const name = file.slice(0, -4);
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name))
      throw new Error(`${file}: expected kebab-case icon name`);
    const source = readFileSync(join(directory, file), "utf8");
    checkIcon(source, file);
    return `  ${JSON.stringify(name)}: ${JSON.stringify(reactTree(parseIcon(source, file)))},`;
  });
  return `// Generated by scripts/generate-icons.ts. Do not edit.\nexport const icons = {\n${entries.join("\n")}\n} as const satisfies Record<IconName, unknown>;\n\n/** Available names generated from the SVG catalogue. */\nexport type IconName =\n${files.map((file) => `  | ${JSON.stringify(file.slice(0, -4))}`).join("\n")};\n`;
}
export function checkIcons(file: string, expected: string) {
  return existsSync(file) && readFileSync(file, "utf8") === expected;
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const output = "src/icon/icons.ts";
  const generated = generateIcons();
  if (process.argv.includes("--check")) {
    if (!checkIcons(output, generated)) {
      console.error(`${output} is stale; run pnpm icons:generate`);
      process.exitCode = 1;
    }
  } else writeFileSync(output, generated);
}
